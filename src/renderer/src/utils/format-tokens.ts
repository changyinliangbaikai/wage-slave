/**
 * 紧凑显示 token 数量的工具函数（顶部 Context 进度、设置页快捷按钮共用）
 *
 * 优先级策略：
 *   1. n 为 1000 的整倍数 → 用十进制 k/M（如 128_000 → "128k"、1_000_000 → "1M"）
 *   2. n 为 1024 的整倍数 → 用 1024 进制 k/M（如 8192 → "8k"、1_048_576 → "1M"）
 *   3. 其它情况：< 10_000 保留 1 位小数；>= 10_000 取整千位
 *
 * 设计目的：让常见模型上下文（8k / 16k / 32k / 64k / 128k / 200k / 240k / 1M）
 * 显示成符合人类直觉的"整数+单位"，避免出现 "8.2k" / "33k" / "66k" 这类
 * 因为单纯按 ÷1000 取整产生的非整数化结果。
 */
export function formatTokens(n: number): string {
  if (!Number.isFinite(n) || n < 0) return '0'
  if (n < 1000) return String(Math.round(n))

  // 1) 十进制整倍数（128_000 / 200_000 / 1_000_000 等）
  if (n % 1000 === 0) {
    if (n >= 1_000_000 && n % 1_000_000 === 0) return `${n / 1_000_000}M`
    return `${n / 1000}k`
  }

  // 2) 1024 进制整倍数（8192 / 16384 / 32768 / 65536 / 245760 / 1048576 等）
  if (n % 1024 === 0) {
    const k = n / 1024
    if (k >= 1024 && k % 1024 === 0) return `${k / 1024}M`
    return `${k}k`
  }

  // 3) 其它：用十进制紧凑展示
  if (n >= 1_000_000) {
    const m = n / 1_000_000
    return m === Math.floor(m) ? `${m}M` : `${m.toFixed(1)}M`
  }
  if (n < 10_000) return `${(n / 1000).toFixed(1)}k`
  return `${Math.round(n / 1000)}k`
}
